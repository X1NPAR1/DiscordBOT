CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  discordId VARCHAR(32) UNIQUE,
  steamId VARCHAR(32) UNIQUE,
  credit INT DEFAULT 0,
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS market_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  messageId VARCHAR(32),
  buttonCustomId VARCHAR(64),
  displayName VARCHAR(128),
  permissionGroup VARCHAR(64),
  durationHours INT DEFAULT 0,
  price INT NOT NULL,
  createdBy VARCHAR(32),
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS permission_grants (
  id INT AUTO_INCREMENT PRIMARY KEY,
  steamId VARCHAR(32),
  permissionGroup VARCHAR(64),
  grantedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  expiresAt TIMESTAMP NULL,
  revokeStatus ENUM('active','revoked') DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS link_codes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  steamId VARCHAR(32),
  code VARCHAR(16) UNIQUE,
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  expiresAt TIMESTAMP,
  used TINYINT(1) DEFAULT 0
);

CREATE TABLE IF NOT EXISTS linked_accounts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  discordId VARCHAR(32) UNIQUE,
  steamId VARCHAR(32) UNIQUE,
  linkedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  rewardGiven TINYINT(1) DEFAULT 0
);
